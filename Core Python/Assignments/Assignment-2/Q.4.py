# 4. WAP to calculate area of triangle and rectangle


base = int(input('Ener the base of the triangle : '))
height = int(input('Enter the height of the triangle : '))
area_of_triangle = 0.5 * base * height
print(f' area of triangle is : {area_of_triangle}')


length = int(input('Enter the length of the rectangle : '))
breath = int(input('Enter the breath of the rectangle : '))
area_of_rectangle = length * breath
print(f' area of rectangle is : {area_of_rectangle}')